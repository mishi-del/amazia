function countKeyMatches(lower, keys) {
  return keys.filter((k) => lower.includes(k)).length
}

/**
 * @param {string} message
 * @returns {string}
 */
export function guideReply(message) {
  const lower = String(message || '').toLowerCase().trim()

  if (!lower) {
    return 'Ask me about Barrier Support Serum — ingredients, routine, results, shipping, or where to find something on this page.'
  }

  if (/\b(hi|hello|hey|salam|assalam|good morning|good evening)\b/.test(lower)) {
    return 'Hello! I am AMAZIA Guide — free help on this page. Ask about the serum, how to use it, shipping, bundles, or say “where is FAQ” to jump to a section.'
  }

  if (/\b(thanks|thank you|shukriya|ok thanks|got it)\b/.test(lower)) {
    return 'You are welcome! If you need anything else about Barrier Support Serum or this page, just ask.'
  }

  if (/\b(bye|goodbye|see you)\b/.test(lower)) {
    return 'Take care — and give your barrier time to strengthen. Come back anytime you have questions.'
  }

  if (/\b(where|find|scroll|section|navigate|go to)\b/.test(lower)) {
    let best = null
    let bestScore = 0
    for (const hint of SECTION_HINTS) {
      const score = countKeyMatches(lower, hint.keys)
      if (score > bestScore) {
        bestScore = score
        best = hint
      }
    }
    if (best) return best.answer
  }

  let bestFaq = null
  let bestFaqScore = 0
  for (const item of FAQ_SNIPPETS) {
    const score = countKeyMatches(lower, item.keys)
    if (score > bestFaqScore) {
      bestFaqScore = score
      bestFaq = item
    }
  }
  if (bestFaq) return bestFaq.answer

  return 'I can help with Barrier Support Serum — ingredients (#ingredients), how to use it, results (7–14 days for tightness; 4–6 weeks for barrier support), price (Rs. 3,800), shipping & COD, bundles (#bundles), reviews (#write-review), or 10% off (#offer). What would you like to know?'
}

/** @deprecated Use guideReply */
export function fallbackGuideReply(message) {
  return guideReply(message)
}
